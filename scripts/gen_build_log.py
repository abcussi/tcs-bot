"""Regenerate docs/BUILD_LOG.md from `git log --reverse`, grouped by project phase.

Run: uv run python scripts/gen_build_log.py

A phase starts at the commit whose abbreviated hash is listed below; every later commit belongs
to it until the next phase starts. New commits after the last boundary land in the last phase.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

# (first commit hash prefix, title, what happened)
PHASES: list[tuple[str, str, str]] = [
    (
        "50d42c8",
        "1. Scaffold and orchestration",
        "uv workspace, SDD specs, AI harness, compose, CLI.",
    ),
    (
        "c13812a",
        "2. Google Finance crawler",
        "Parser, scraper, Elasticsearch sink, cron entrypoint.",
    ),
    ("69f7254", "3. Data layer", "MySQL pool/transactions, schema, repositories, cache, search."),
    (
        "fb9a0a8",
        "4. Report generator",
        "Schemas, errors, ingestion, RAG, LCEL chain, service, API, MCP, tests.",
    ),
    (
        "9640e6d",
        "5. Architecture review and hardening",
        "Fixes from the review; integration and e2e suites.",
    ),
    (
        "0df400e",
        "6. Rename, CI and live smoke tests",
        "Package renamed to tcs-bot; GitHub Actions; OpenAI smoke.",
    ),
    (
        "4aa56b4",
        "7. Medallion foundations (spec 005)",
        "Spec, deps, shared models, config, CLI, Qdrant in compose.",
    ),
    (
        "f140008",
        "8. Medallion layers (bronze, silver, gold)",
        "Crawler sources + BFS, silver extraction/rules/ES, gold LSA/graph (vectors were in Qdrant "
        "at this point, moved to Elasticsearch in phase 10). "
        "The wip(...) commits hold this code; it was verified later, see phases 9 and 10.",
    ),
    (
        "a6e0f4e",
        "9. Handoff and first local verification",
        "First run on a real machine: real-internet crawl fixes, CI Qdrant service, README, "
        "graph page checked in a real browser.",
    ),
    (
        "147ec8e",
        "10. Real-data tuning, Elasticsearch gold, read layer",
        "Silver relevance/risk tuned on real crawled docs, gold dedupe and clustering, "
        "gold vectors moved to Elasticsearch (Qdrant dropped), cross-run Bing dedupe, "
        "typed read layer + API/MCP tools, data dictionary.",
    ),
]


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    out = subprocess.run(
        ["git", "log", "--reverse", "--format=%h%x09%ad%x09%s", "--date=short"],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    ).stdout
    commits = [line.split("\t", 2) for line in out.splitlines() if line.strip()]
    starts = {h: i for i, (h, _, _) in enumerate(PHASES)}
    groups: list[list[list[str]]] = [[] for _ in PHASES]
    current = -1
    for c in commits:
        for prefix, idx in starts.items():
            if c[0].startswith(prefix[:7]) or prefix.startswith(c[0]):
                current = idx
        if current < 0:
            raise SystemExit(f"commit {c[0]} precedes the first phase boundary")
        groups[current].append(c)

    lines = [
        "# Build log",
        "",
        "Generated by `scripts/gen_build_log.py` from `git log --reverse`. Do not edit by hand.",
        f"{len(commits)} commits.",
        "",
    ]
    for (_, title, blurb), items in zip(PHASES, groups, strict=True):
        if not items:
            continue
        lines += [f"## {title}", "", blurb, ""]
        lines += [f"- `{h}` {d} — {s}" for h, d, s in items]
        lines.append("")
    path = root / "docs" / "BUILD_LOG.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {path} ({len(commits)} commits)")


if __name__ == "__main__":
    main()
